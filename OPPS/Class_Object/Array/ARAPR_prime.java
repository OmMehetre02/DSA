/*Q8. Count the number of prime numbers in an array.
Input: arr = [2, 5, 6, 9, 11]
Output: Count of prime numbers = 3
*/
public class ARAPR_prime{
public static void main(String[]args){
	int count=0;
	int i;
	for(i=2;i<=100;i++){
		if(i%1==0){
			count++;
		}
	}
	if(i==2){
		
			System.out.print("\t"+i);
		
	}
}
}